const assert=require('node:assert/strict');
const fs=require('fs');
assert.ok(fs.existsSync(__dirname+'/translation-classified-export.js'),'缺少分类导出模块');
const {buildClassifiedWorkbook}=require('./translation-classified-export');
const X=require('xlsx-js-style');
const task={headers:['id','id','en'],data:[[1,'a','=Hello'],[2,'b','Hi'],[3,'c','']],columnIndex:2,targetLangs:['es','ja']};
const results=[{id:'a',rowIndex:0,targetLang:'es',translation:'Hola',route:'auto'},{id:'b',rowIndex:0,targetLang:'ja',translation:'こんにちは',route:'human',reviewReason:'检查语气'},{id:'c',rowIndex:1,targetLang:'es',translation:'Hola',route:'spot_check',reviewReason:'抽查'},{id:'d',rowIndex:1,targetLang:'ja',translation:['やあ','こんにちは'],route:'auto'}];
const make=(kind,reviews=[])=>buildClassifiedWorkbook(task,results,reviews,kind,l=>l);
const wb=make('human');const s=wb.Sheets[wb.SheetNames[0]];
assert.deepEqual(X.utils.sheet_to_json(s,{header:1,defval:''})[0],['id','id','en','es','es复审原因','ja','ja复审原因']);
assert.equal(s.C2.v,'=Hello');assert.equal(s.C2.f,undefined);assert.equal(s.F2.s.fill.fgColor.rgb,'FFF2CC');assert.equal(s.D2.s,undefined);
assert.equal(X.utils.sheet_to_json(s,{header:1}).length,3);
assert.equal(X.utils.sheet_to_json(make('approved').Sheets['翻译结果'],{header:1}).length,2);
assert.equal(X.utils.sheet_to_json(make('spot_check').Sheets['翻译结果'],{header:1}).length,2);
const fixed=make('approved',[{resultId:'b',decision:'fix',finalText:'修正訳'}]);assert.equal(fixed.Sheets['翻译结果'].E2.v,'修正訳');
assert.equal(fixed.Sheets['翻译结果'].E3.v,'["やあ","こんにちは"]');
const buffer=X.write(wb,{type:'buffer',bookType:'xlsx'});const read=X.read(buffer,{type:'buffer',cellStyles:true});assert.equal(read.Sheets['翻译结果'].F2.s.fgColor.rgb,'FFF2CC');
assert.throws(()=>buildClassifiedWorkbook(task,[...results,results[0]],[],'human'),/重复/);
console.log('PASS: 分类、原重复列、公式文本、单格高亮、缺失、人工覆盖、结构化译文、xlsx样式回读、重复防护');
